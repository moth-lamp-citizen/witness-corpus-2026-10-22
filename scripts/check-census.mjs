import { readFileSync } from "node:fs";
const c = JSON.parse(readFileSync(process.env.CENSUS ?? "data/census.json", "utf8"));
const dir = process.env.WITNESS_DIR ?? "sources/witness";
const assert = (name, got, want) => {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  console.log((ok ? "PASS" : "FAIL"), name, "got", JSON.stringify(got), "want", JSON.stringify(want));
  if (!ok) process.exitCode = 1;
};
assert("files", c.files, 65);
assert("rows", c.rows, 39789);
assert("countersigned", c.countersigned, 26685);
assert("firstObservation", c.firstObservation.length, 2);
assert("fromRows", c.fromRows, 26683);
assert("sameSize", c.sameSize, 19910);
assert("growth", c.growth, 6773);
assert("crossFilePrior", c.crossFilePrior, 50);
const cross = c.crossFileRows;
assert("crossFileRows", cross.length, 50);
const growthCross = cross.filter((x) => x.from < x.tree_size);
assert("crossFileGrowth", growthCross.length, 36);
assert("crossFileGrowthDays", new Set(growthCross.map((x) => x.file)).size, 35);
const last = cross.find((x) => x.file === "2026-10-21.jsonl");
assert("lastFirstLine", [last.log, last.tree_size, last.from, last.priorIn], ["identity_events", 28815, 28787, ["2026-10-20.jsonl"]]);
const rows = readFileSync(dir + "/2026-08-12.jsonl", "utf8").split("\n").filter(Boolean).map(JSON.parse);
const first = rows.find((r) => r.log === "identity_events" && r.tree_size === 93 && r.consistency === "first observation");
const next = rows.find((r) => r.log === "identity_events" && r.tree_size === 93 && r.consistency === "verified from 93");
assert("firstObs", [first.at, first.tree_size, first.root], ["2026-08-12T12:40:16.267Z", 93, "5f71cbcb65219c6e6a112f7165fdf5e169e1f6690ad6faa5752a9013792e88f4"]);
assert("nextSameRoot", next.root === first.root, true);
assert("deltaSeconds", (Date.parse(next.at) - Date.parse(first.at)) / 1000, 62.088);
console.log("census check complete");
